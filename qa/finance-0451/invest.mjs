export async function run(b,{assert,proof,act,btn,value,nav,wait,close,read,finances,eventually,shot,setDate}) {
  const mark=(p,a,e,v)=>proof("Invest",p,a,e,v);
  const overview=()=>read("invest_overview");
  const capture=async()=>({accounts:(await overview()).accounts,ledger:await finances()});
  const initial=await capture(), account=initial.accounts[0];
  const iso=offset=>{const d=new Date();d.setUTCDate(d.getUTCDate()-offset);return d.toISOString().slice(0,10)};
  let back=1;while(account.history.some(x=>x.date===iso(back)))back++;
  const date=iso(back), history=async()=>(await overview()).accounts.find(x=>x.id===account.id).history;
  const entry=async()=>(await history()).find(v=>v.date===date);
  const launch=()=>act('[data-testid="account-row"][data-name="'+account.name+'"] [data-testid="account-invest-value"]');
  await nav("Счета");await launch();await wait('[role="dialog"]',/Стоимость/);
  proof("Accounts","135:12","Открыть стоимость из строки брокерского счёта","Редактор выбранного счёта",await b.$('[role="dialog"] h2').getText());
  await setDate(b,"investDate",date);await value("investValue","98765");await value("investValue","");
  assert.equal(await b.$('[role="dialog"] [type="submit"]').isEnabled(),false);
  await value("investValue","98765");await close();
  const added=await eventually(entry,v=>v?.value===9876500);
  assert.deepEqual(await finances(),initial.ledger);
  mark("306:6 358:10","Пустое значение, затем запись оценки 98 765 ₽","Пустое значение блокирует сохранение. Записано 9 876 500 коп. без изменения проводок, остатков и доходов",added);
  await launch();await setDate(b,"investDate",date);await value("investValue","11111");await close("Отмена");
  assert.deepEqual(await entry(),added);
  mark("355:10","Отмена исправления оценки","Сохранена прежняя сумма",await entry());
  await launch();await setDate(b,"investDate",date);await value("investValue","87654");await close();
  assert.equal((await entry()).value,8765400);
  assert.equal((await history()).filter(v=>v.date===date).length,1);
  const cells='//*[@data-testid="invest-history"]//tr[contains(translate(normalize-space(td[2])," \u00a0\u202f",""),"87654")]//button';
  await launch();await shot("valuation-edited");await act(cells);
  await eventually(history,v=>!v.some(x=>x.date===date));
  await close("Отмена");
  assert.deepEqual(await capture(),initial);
  mark("343:20","Повторно сохранить дату, затем удалить нужную строку истории","Одна оценка на дату. Удаление полностью возвращает исторические записи и финансовые показатели", {date,history:await history(),ledger:initial.ledger});
  await nav("Главная");
  const plan=async()=>(await overview()).month.plan;
  const planOpen=()=>act('[data-testid="home-invest"] [data-testid="invest-plan-edit"]');
  const initialPlan=await plan();
  await planOpen();await act('[data-testid="invest-plan-percent"]');await value("investPlanPercent","101");await btn("Сохранить",true);await wait('[role="dialog"]',/от 1 до 100/);assert.deepEqual(await plan(),initialPlan);
  await value("investPlanPercent","17");await close();let saved=await plan();assert.equal(saved.mode,"percent");assert.equal(saved.value,17);
  mark("228:6 236:10","Проверка 101%, затем запись 17%","101% отклонён, 17% сохранены",saved);
  await planOpen();await value("investPlanPercent","44");await close("Отмена");assert.deepEqual(await plan(),saved);
  mark("274:10","Отменить изменение плана на 44%","Действуют 17%",await plan());
  await nav("Бюджет");await act('[data-testid="plan-fact-invest-edit"]');await act('[data-testid="invest-plan-percent"]');await value("investPlanPercent","23");await act('[name="investOnlyMonth"]');await close();assert.equal((await plan()).onlyMonth,true);
  await act('[data-testid="plan-fact-invest-edit"]');await close("Вернуть общий план");assert.deepEqual(await plan(),saved);
  mark("263:12","Сохранить план месяца 23%, вернуть общий план","Снова общий 17%",await plan());
  await nav("Главная");await planOpen();await close("Убрать план");assert.ok(!(await plan()).mode);
  mark("268:14","Убрать общий план","Режим плана пуст",await plan());
}
